def 计算平均年龄(用户列表):
    总年龄 = 0
    for 用户 in 用户列表:
        总年龄 += 用户.年龄
    return 总年龄 / len(用户列表)

def 搜索用户(用户列表, 关键词):
    搜索结果 = []
    for 用户 in 用户列表:
        if 关键词 in 用户.姓名:
            搜索结果.append(用户)
    return 搜索结果

